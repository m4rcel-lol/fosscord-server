export const locale = () => document.documentElement.lang || navigator.language || "en-US";

export const t = (text: string, vars: Record<string, string | number> = {}) => {
    const lang = locale();
    const index = LOCALES.findIndex((x) => x === lang || x === lang.split("-")[0]);
    const translated = (index === -1 ? undefined : STRINGS[text]?.[index]) ?? text;
    return translated.replace(/\{(\w+)\}/g, (match, key: string) => (key in vars ? String(vars[key]) : match));
};

export const conjunction = (items: string[]) => new Intl.ListFormat(locale(), { type: "conjunction" }).format(items);
