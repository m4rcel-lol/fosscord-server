// how many of the server's badge colours a badge uses, which the client uses to decide whether to offer the accent colour
export const clanBadgeColorCount = (badge: CustomClanBadge) => {
    const shades = Object.values(badge.palette).filter((fill): fill is ClanBadgeShade => typeof fill === "object");
    return shades.some((shade) => shade.ch === "S") ? 2 : 1;
};

export const customClanBadge = (id: number | string | null | undefined) => CUSTOM_CLAN_BADGES.find((badge) => badge.id === Number(id));

// the pack a badge is listed under
export const clanBadgePack = (badge: CustomClanBadge) => badge.pack ?? CUSTOM_CLAN_BADGE_PACK;

export const isStaffOnlyClanBadge = (id: number | string | null | undefined) => !!customClanBadge(id)?.staff_only;
