// server tag badges this instance adds to the client's own. Each is 16x16 pixel art: a grid of palette keys, where a colour
// is fixed or follows the server's badge colours the way the client's badges do: the main (P) or accent (S) colour moved to
// luminance c0 + c1 * luminance(colour), or `def` when the server keeps the badge's own colours. A staff-only one can only
// be put on a server from the admin panel
export type ClanBadgeShade = { ch: "P" | "S"; c0: number; c1: number; def: string };

export interface CustomClanBadge {
    id: number; // well clear of the client's badge ids
    name: string;
    staff_only: boolean;
    pack?: string; // CUSTOM_CLAN_BADGE_PACK when left out
    grid: string[];
    palette: Record<string, string | ClanBadgeShade>;
}

// the client's own shading steps: a dark, base and light tone of the main or accent colour, plus a deeper one for shadows
const TONES = { deep: [0.06, 0.08], dark: [1 / 6, 1 / 6], base: [0.375, 0.25], light: [0.6, 0.25] } as const;
const main = (tone: keyof typeof TONES, def: string): ClanBadgeShade => ({ ch: "P", c0: TONES[tone][0], c1: TONES[tone][1], def });
const accent = (tone: keyof typeof TONES, def: string): ClanBadgeShade => ({ ch: "S", c0: TONES[tone][0], c1: TONES[tone][1], def });

// the pack the instance's badges are grouped under in the client's badge picker and the admin panel, unless a badge names its own
export const CUSTOM_CLAN_BADGE_PACK = "Custom Icon Pack";

